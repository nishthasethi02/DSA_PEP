/*
    A Graph G = (V, E) consisits of :
    V -> Set of vertices(nodes) -> An individual object in a graph.
    E -> Set of edges connecting pairs of vertices

    Directed Graph -> Edges have directions
    Undirected Graph -> Edges have no direction
    Weighted Graph -> Edges have values (weights / costs / distances)
    Unweighted Graph -> Edges have no values
    
    Path -> A sequence of vertices connected by edges
    Cycle -> A path that starts and ends at the same vertex.
    Degree -> to one node how many nodes are connected? -> Undirected
           -> In degree -> to one node how many nodes are coming? -> Directed Graph
           -> out degree -> Directed -> Outgoing edges from a node

*/